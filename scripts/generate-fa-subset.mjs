// Generates a Font Awesome subset (CSS + woff2) containing only the icons used in src/.
// Run after adding/removing fa-* icons anywhere in src: node scripts/generate-fa-subset.mjs
// Output: src/assets/fontawesome/ (imported by BaseLayout.astro instead of all.min.css)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const faDir = join(root, "node_modules/@fortawesome/fontawesome-free");
const outDir = join(root, "src/assets/fontawesome");

// ---------- 1. Scan src/ for fa-* classes ----------
const SCAN_EXT = /\.(astro|ts|js|mjs|jsx|tsx|json|md|mdx|html|css)$/;
const used = new Set();
function scan(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (p.startsWith(outDir)) continue; // don't scan our own output
    if (statSync(p).isDirectory()) scan(p);
    else if (SCAN_EXT.test(name)) {
      for (const m of readFileSync(p, "utf8").matchAll(/\bfa-[a-z0-9][a-z0-9-]*/g)) {
        used.add(m[0].replace(/^fa-/, ""));
      }
    }
  }
}
scan(join(root, "src"));

// Non-icon utility classes we support. Anything else not found in icon
// metadata is an error so a typo or an unsupported modifier fails the build.
const SUPPORTED_MODIFIERS = new Set(["solid", "brands", "lg", "xl", "bounce"]);

// ---------- 2. Resolve icon names -> unicode + family ----------
const meta = JSON.parse(readFileSync(join(faDir, "metadata/icon-families.json"), "utf8"));
const byName = new Map();
for (const [name, icon] of Object.entries(meta)) {
  const styles = (icon.familyStylesByLicense?.free ?? []).map((s) => s.style);
  if (!styles.length) continue;
  const entry = { unicode: icon.unicode, brands: styles.includes("brands") };
  byName.set(name, entry);
  for (const alias of icon.aliases?.names ?? []) if (!byName.has(alias)) byName.set(alias, entry);
}

const icons = [];
const unknown = [];
for (const name of [...used].sort()) {
  if (SUPPORTED_MODIFIERS.has(name)) continue;
  const icon = byName.get(name);
  if (icon) icons.push({ name, ...icon });
  else unknown.push(name);
}
if (unknown.length) {
  throw new Error(`Unknown fa- classes (not icons, not supported modifiers): ${unknown.join(", ")}`);
}

// ---------- 3. Subset the woff2 fonts ----------
mkdirSync(outDir, { recursive: true });
async function subset(srcFont, outFont, glyphs) {
  const text = glyphs.map((i) => String.fromCodePoint(parseInt(i.unicode, 16))).join("");
  const buf = await subsetFont(readFileSync(join(faDir, "webfonts", srcFont)), text, { targetFormat: "woff2" });
  writeFileSync(join(outDir, outFont), buf);
  return buf.length;
}
const solidIcons = icons.filter((i) => !i.brands);
const brandIcons = icons.filter((i) => i.brands);
const solidSize = await subset("fa-solid-900.woff2", "fa-solid-900.subset.woff2", solidIcons);
const brandsSize = await subset("fa-brands-400.woff2", "fa-brands-400.subset.woff2", brandIcons);

// ---------- 4. Generate CSS (base rules extracted from the installed FA css) ----------
const faCss = readFileSync(join(faDir, "css/all.min.css"), "utf8");
function extract(regex, label) {
  const m = faCss.match(regex);
  if (!m) throw new Error(`Could not extract ${label} from all.min.css — FA version changed?`);
  return m[0];
}
const baseBlock = extract(/\.fa,\.fa-brands[^{]*\{[^}]*\}/, "base block");
const beforeBlock = extract(/:is\([^)]*\):before\{[^}]*\}/, ":before block");
const supportsBlock = extract(/@supports not \(content:""\/""\)\{[^{}]*\{[^}]*\}\}/, "@supports fallback");
const brandsStyle = extract(/\.fa-brands,\.fa-classic\.fa-brands,\.fab\{[^}]*\}/, "brands style");
const solidStyle = extract(/\.fa-solid\{[^}]*\}/, "solid style");
const faLg = extract(/\.fa-lg\{[^}]*\}/, "fa-lg");
const faXl = extract(/\.fa-xl\{[^}]*\}/, "fa-xl");
const faBounce = extract(/\.fa-bounce\{[^}]*\}/, "fa-bounce");
const bounceKeyframes = extract(/@keyframes fa-bounce\{.*?\}\}/s, "fa-bounce keyframes");

const iconRules = icons.map((i) => `.fa-${i.name}{--fa:"\\${i.unicode}"}`).join("\n");

const css = `/* Generated by scripts/generate-fa-subset.mjs — do not edit by hand.
 * Subset of @fortawesome/fontawesome-free covering only the icons used in src/. */
:host,:root{--fa-family-brands:"Font Awesome 7 Brands";--fa-font-brands:normal 400 1em/1 var(--fa-family-brands);--fa-family-classic:"Font Awesome 7 Free";--fa-font-solid:normal 900 1em/1 var(--fa-family-classic);--fa-style-family-classic:var(--fa-family-classic)}
@font-face{font-family:"Font Awesome 7 Free";font-style:normal;font-weight:900;font-display:swap;src:url(./fa-solid-900.subset.woff2) format("woff2")}
@font-face{font-family:"Font Awesome 7 Brands";font-style:normal;font-weight:400;font-display:swap;src:url(./fa-brands-400.subset.woff2) format("woff2")}
${baseBlock}
${beforeBlock}
${supportsBlock}
${solidStyle}
${brandsStyle}
${faLg}
${faXl}
${faBounce}
${bounceKeyframes}
${iconRules}
`;
writeFileSync(join(outDir, "fontawesome-subset.css"), css);

console.log(`Icons: ${solidIcons.length} solid + ${brandIcons.length} brands`);
console.log(`fa-solid-900.subset.woff2: ${(solidSize / 1024).toFixed(1)} KB`);
console.log(`fa-brands-400.subset.woff2: ${(brandsSize / 1024).toFixed(1)} KB`);
console.log(`fontawesome-subset.css: ${(css.length / 1024).toFixed(1)} KB`);
